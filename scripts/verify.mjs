import puppeteer from 'puppeteer-core';
import fs from 'node:fs';
const base = process.env.TEST_URL || 'http://127.0.0.1:4321/';
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const results = [];
const check = (name, pass, detail = null) => { results.push({ name, pass: Boolean(pass), detail }); console.log(`${pass ? 'PASS' : 'FAIL'} ${name}${detail ? ': ' + JSON.stringify(detail) : ''}`); };
const wait = ms => new Promise(r => setTimeout(r, ms));
try {
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.setViewport({ width: 1440, height: 900, deviceScaleFactor: 1 });
  await page.goto(base + '?lang=zh', { waitUntil: 'networkidle0' });
  await page.waitForFunction(() => document.documentElement.classList.contains('intro-done'));
  await wait(1300);
  await page.screenshot({ path: 'qa/desktop-hero.png' });
  check('One semantic h1', await page.$$eval('h1', es => es.length === 1));
  check('Real library controls rendered', await page.$$eval('button[class*="animal-btn"]', es => es.length >= 5));
  const initial = await page.$eval('#heroCat [data-cat]', e => e.getAttribute('data-cat'));
  await page.click('#heroCat'); await wait(800);
  check('Cat pointer changes one form', await page.$eval('#heroCat [data-cat]', e => e.getAttribute('data-cat')) === 'kaito', initial);
  await page.focus('#heroCat'); await page.keyboard.press('Enter'); await wait(800);
  check('Cat keyboard changes one form', await page.$eval('#heroCat [data-cat]', e => e.getAttribute('data-cat')) === 'kurumi');
  await page.click('#langBtn');
  check('Language changes to English', await page.$eval('html', e => e.lang) === 'en');
  check('English card content', await page.$eval('[data-i18n="c1t"]', e => e.textContent.includes('Learning')));
  await page.click('#langBtn');
  await page.click('.intro-p .mark');
  check('Annotation opens on click', await page.$eval('.intro-p .mark', e => e.classList.contains('open')));
  await page.keyboard.press('Escape');
  check('Escape dismisses annotation', await page.$$eval('.mark.open', es => es.length === 0));
  await page.focus('#thief'); await page.keyboard.press('Enter'); await wait(700);
  check('Calling card opens', await page.$eval('#cc', e => !e.hidden));
  check('Dialog focus moved to close', await page.evaluate(() => document.activeElement.classList.contains('cc-x')));
  await page.screenshot({ path: 'qa/calling-card.png' });
  await page.keyboard.press('Escape'); await wait(400);
  check('Dialog closes and restores focus', await page.evaluate(() => document.querySelector('#cc').hidden && document.activeElement.id === 'thief'));
  await page.evaluate(() => window.scrollTo({ top: 1000, behavior: 'instant' })); await wait(1200);
  await page.screenshot({ path: 'qa/desktop-recent.png' });
  check('Scroll buddy appears', await page.$eval('#buddy', e => e.classList.contains('show')));
  await page.click('#buddy'); await wait(1500);
  check('Back to top', await page.evaluate(() => scrollY < 5));
  await page.click('#motionToggle');
  check('Pause control', await page.$eval('html', e => e.classList.contains('motion-paused')));
  await page.click('#motionToggle');
  await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }]); await wait(100);
  check('Live reduced-motion preference', await page.$eval('html', e => e.classList.contains('rm')));
  for (const width of [320, 375, 414, 560, 768, 900, 901, 1024, 1280, 1440, 1920]) {
    await page.setViewport({ width, height: width < 600 ? 812 : 900, deviceScaleFactor: 1 });
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' })); await wait(80);
    const sizes = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth, body: document.body.scrollWidth }));
    check(`No horizontal overflow ${width}`, sizes.document <= width && sizes.body <= width, sizes);
    if (width === 375) await page.screenshot({ path: 'qa/mobile-full.png', fullPage: true });
    if (width === 1440) await page.screenshot({ path: 'qa/desktop-full.png', fullPage: true });
  }
  await page.setViewport({ width: 1280, height: 800 });
  check('Hero fits 1280×800', await page.$eval('.ctas', e => e.getBoundingClientRect().bottom <= 800));
  const nojs = await browser.newPage();
  await nojs.setJavaScriptEnabled(false); await nojs.setViewport({ width: 375, height: 812 });
  await nojs.goto(base, { waitUntil: 'networkidle0' });
  check('No-JS intro is not blocking', await nojs.$eval('#intro', e => getComputedStyle(e).display === 'none'));
  check('No-JS cats rendered by Astro', await nojs.$$eval('[data-cat] svg', es => es.length >= 10));
  check('No-JS content visible', await nojs.$eval('.hero-copy', e => getComputedStyle(e).opacity === '1'));
  await nojs.screenshot({ path: 'qa/no-js-mobile.png' });
  check('No browser runtime errors', errors.length === 0, errors);
} finally {
  await browser.close();
  fs.writeFileSync('qa/browser-results.json', JSON.stringify({ date: '2026-10-27', results, passed: results.filter(r => r.pass).length, failed: results.filter(r => !r.pass).length }, null, 2));
}
if (results.some(r => !r.pass)) process.exitCode = 1;
